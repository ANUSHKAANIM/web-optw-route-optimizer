// Delhi / NCR tourist places dataset for route-optimization game.
// Coordinates and opening hours are based on real-world knowledge of these
// places. Where the exact weekly schedule was uncertain (seasonal variation,
// restricted/protocol access, informal sites, prayer-time closures not
// modeled, etc.) `approximateHours` is set to true so it can be spot-checked.

export interface DayHours {
  open: string; // "HH:MM" 24h, Delhi/India local time (IST)
  close: string; // "HH:MM"
  closed?: boolean; // true if closed all day this weekday
}

export interface OpeningHours {
  monday: DayHours;
  tuesday: DayHours;
  wednesday: DayHours;
  thursday: DayHours;
  friday: DayHours;
  saturday: DayHours;
  sunday: DayHours;
}

export interface DelhiPlace {
  id: string; // snake_case unique slug, e.g. "qutub_minar"
  name: string; // display name
  category: string; // e.g. "monument", "temple", "museum", "garden", "market", "memorial"
  latitude: number; // real-world decimal degrees
  longitude: number; // real-world decimal degrees
  openingHours: OpeningHours;
  visitDurationMinutes: number; // realistic typical visit length
  baseReward: number; // 40-150 range, roughly proportional to popularity/significance
  approximateHours: boolean; // true if you are not confident the hours are precisely accurate
}

type Weekday = keyof OpeningHours;

const WEEKDAYS: Weekday[] = [
  "monday",
  "tuesday",
  "wednesday",
  "thursday",
  "friday",
  "saturday",
  "sunday",
];

/**
 * Builds a full-week OpeningHours object with the same open/close time every
 * day, except for the weekdays listed in `closedDays`, which are marked
 * closed all day.
 */
function daily(open: string, close: string, closedDays: Weekday[] = []): OpeningHours {
  const result = {} as OpeningHours;
  for (const day of WEEKDAYS) {
    if (closedDays.includes(day)) {
      result[day] = { open: "00:00", close: "00:00", closed: true };
    } else {
      result[day] = { open, close };
    }
  }
  return result;
}

